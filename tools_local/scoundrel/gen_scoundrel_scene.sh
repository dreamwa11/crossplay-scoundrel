#!/bin/bash
# Regenerate src/apps_local/scoundrel/ScoundrelScene.h: the room scenes above the
# cards (480x178, 1-bit), four kinds taken in turn (draw_scene.py draws the
# doorway hall, draw_rooms.py the rest), and the end screens' pictures
# (480x380). Rooms are drawn at half strength (every other black pixel knocked
# out) so they read as grey and the cards stay in front.
# Needs rsvg-convert and Pillow.
set -euo pipefail
REPO="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../.." && pwd)"
cd "$REPO"
OUT=src/apps_local/scoundrel/ScoundrelScene.h
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
# Four kinds of room, taken in turn: the doorway hall, a corner with a barred
# window, a beamed cellar, a pillared crypt.
KINDS=(hall window cellar crypt)
SEEDS=("${KINDS[@]}")
for i in "${!KINDS[@]}"; do
  if [ "${KINDS[$i]}" = hall ]; then
    python3 tools_local/scoundrel/draw_scene.py "$TMP/scene$i.svg" 7
  else
    python3 tools_local/scoundrel/draw_rooms.py "${KINDS[$i]}" "$TMP/scene$i.svg"
  fi
  rsvg-convert "$TMP/scene$i.svg" -o "$TMP/scene$i.png"
done
# The death screen's picture: wall and floor at half strength, the grave in full.
FACE="$(python3 tools_local/scoundrel/draw_died.py "$TMP/died")"
rsvg-convert "$TMP/died_back.svg" -o "$TMP/died_back.png"
rsvg-convert "$TMP/died_front.svg" -o "$TMP/died_front.png"
# And the survivor's: the last archway, and the daylight through it.
python3 tools_local/scoundrel/draw_survived.py "$TMP/survived"
rsvg-convert "$TMP/survived_back.svg" -o "$TMP/survived_back.png"
rsvg-convert "$TMP/survived_front.svg" -o "$TMP/survived_front.png"
python3 - "$TMP" "$OUT" "${#SEEDS[@]}" "$FACE" <<'PY'
import sys
from PIL import Image
tmp, out, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
lines = ['#pragma once', '', '// Scoundrel room scenes. Generated by tools_local/scoundrel/gen_scoundrel_scene.sh; do not edit.', '',
         '#include "Icon.h"', '']
for i in range(n):
    im = Image.open(f'{tmp}/scene{i}.png').convert('RGBA')
    bg = Image.new('RGBA', im.size, 'white'); bg.paste(im, mask=im.split()[3])
    g = bg.convert('L'); w, h = g.size; px = g.load()
    data = []
    for y in range(h):
        for bx in range(0, w, 8):
            b = 0
            for k in range(8):
                x = bx + k
                white = x >= w or px[x, y] >= 128 or (x + y) % 2 == 1
                b = (b << 1) | (1 if white else 0)
            data.append(b)
    lines.append(f'static const uint8_t scene_room{i}_bits[] = {{' + ','.join(f'0x{b:02X}' for b in data) + '};')
    lines.append(f'static const freeink::Icon scene_room{i} = {{{w}, {h}, {h // 2}, scene_room{i}_bits}};')
# The end pictures: back layer knocked out like the rooms, front layer on top.
def layered(name):
    back = Image.open(f'{tmp}/{name}_back.png').convert('RGBA'); front = Image.open(f'{tmp}/{name}_front.png').convert('RGBA')
    w, h = back.size; bp = back.load(); fp = front.load()
    data = []
    for y in range(h):
        for bx in range(0, w, 8):
            b = 0
            for k in range(8):
                x = bx + k
                white = True
                if x < w:
                    r, g, bl, a = fp[x, y]
                    if a > 128:
                        white = (r * 299 + g * 587 + bl * 114) / 1000 >= 128
                    else:
                        r, g, bl, a = bp[x, y]
                        dark = a > 128 and (r * 299 + g * 587 + bl * 114) / 1000 < 128
                        white = not dark or (x + y) % 2 == 1
                b = (b << 1) | (1 if white else 0)
            data.append(b)
    lines.append(f'static const uint8_t scene_{name}_bits[] = {{' + ','.join(f'0x{b:02X}' for b in data) + '};')
    lines.append(f'static const freeink::Icon scene_{name} = {{{w}, {h}, {h // 2}, scene_{name}_bits}};')
layered('died')
layered('survived')
_, fx, fy, fw, fh = sys.argv[4].split()
lines.append(f'// The tombstone\'s blank face, inside scene_died.')
lines.append(f'static constexpr int16_t kDiedFaceX = {fx}, kDiedFaceY = {fy}, kDiedFaceW = {fw}, kDiedFaceH = {fh};')
lines.append(f'static const freeink::Icon* const kRoomScenes[] = {{' + ', '.join(f'&scene_room{i}' for i in range(n)) + '};')
lines.append(f'static constexpr int kRoomSceneCount = {n};')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out)
PY
