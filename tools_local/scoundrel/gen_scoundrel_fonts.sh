#!/bin/bash
# Regenerate Scoundrel's font cuts in src/apps_local/scoundrel/fonts/.
#
# The faces of the phone version, all SIL OFL (texts in fonts/source/):
#   Astloch Bold      the "Scoundrel" logo
#   Grenze Bold       card values, the room's name, health and score
#                     (replaced Pirata One, whose J read as a 1)
#   Space Grotesk     everything else, instanced at a fixed weight
#
# 1-bit, ASCII plus two symbols: GfxRenderer's black-and-white path floods antialiased
# cuts, and nothing here needs more than ASCII. Sizes are fontconvert's (points
# at 150 dpi): a size of 9 is a line about 19px tall.
#
# Needs: freetype-py and fonttools (pip install freetype-py fonttools).
set -euo pipefail
REPO="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../.." && pwd)"
cd "$REPO"
SRC=src/apps_local/scoundrel/fonts/source
OUT=src/apps_local/scoundrel/fonts
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

python3 - "$SRC" "$WORK" <<'PY'
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
src, work = sys.argv[1], sys.argv[2]
def cut(path, out, wght=None):
    font = TTFont(path)
    if wght is not None:
        instancer.instantiateVariableFont(font, {"wght": wght}, inplace=True)
    opts = subset.Options()
    sub = subset.Subsetter(opts)
    # ASCII, plus the en dash of a spent choice and the less-or-equal of "Hits <= 9".
    sub.populate(unicodes=list(range(0x20, 0x7F)) + [0x2013, 0x2264])
    sub.subset(font)
    font.save(f"{work}/{out}.ttf")
cut(f"{src}/Astloch-Bold.ttf", "astloch")
cut(f"{src}/Grenze[wght].ttf", "grenze", 700)
cut(f"{src}/SpaceGrotesk[wght].ttf", "grotesk500", 500)
cut(f"{src}/SpaceGrotesk[wght].ttf", "grotesk600", 600)
PY

gen() {  # name size ttf
  python3 lib/EpdFont/scripts/fontconvert.py "$1" "$2" "$WORK/$3.ttf" \
    --additional-intervals 0x2013,0x2013 --additional-intervals 0x2264,0x2264 2>/dev/null | grep -v "extracted$" \
    | sed "s| \* Command used: .*| * Command used: tools_local/scoundrel/gen_scoundrel_fonts.sh ($1 $2 $3)|" > "$OUT/$1.h"
  echo "wrote $OUT/$1.h"
}
gen scnd_logo 22 astloch
gen scnd_value 21 grenze
gen scnd_value_big 30 grenze
gen scnd_small 7 grotesk600
gen scnd_body 9 grotesk500
gen scnd_large 11 grotesk500

# The metrics inkCentred needs (line box, ascender, cap height), read back out
# of the headers just written so they cannot disagree with them.
python3 - "$OUT" <<'PY'
import re, sys, glob, os
out = sys.argv[1]
lines = ["#pragma once", "",
         "// Generated by tools_local/scoundrel/gen_scoundrel_fonts.sh; do not edit.",
         "// Line box, ascender and cap ('H') height of each Scoundrel cut.", "",
         '#include "../../ui/ToyboxTokens.h"', "", "namespace scoundrelfonts {", ""]
for path in sorted(glob.glob(f"{out}/scnd_*.h")):
    name = os.path.basename(path)[:-2]
    text = open(path).read()
    body = text[text.index(f"EpdFontData {name} = {{"):]
    vals = [v.strip() for v in body.split("{", 1)[1].split(",")]
    advance_y, ascender = int(vals[4]), int(vals[5])
    h = re.search(r"\{\s*\d+,\s*(\d+),[^}]*\},\s*// H\n", text)
    ident = "k" + "".join(p.capitalize() for p in name.split("_")[1:]) + "Cut"
    lines.append(f"constexpr toybox::CutMetrics {ident}{{{advance_y}, {ascender}, {h.group(1)}}};  // {name}")
lines += ["", "}  // namespace scoundrelfonts", ""]
open(f"{out}/ScoundrelCuts.h", "w").write("\n".join(lines))
print(f"wrote {out}/ScoundrelCuts.h")
PY
