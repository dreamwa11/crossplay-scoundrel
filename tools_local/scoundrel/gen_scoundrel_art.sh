#!/bin/bash
# Regenerate src/apps_local/scoundrel/ScoundrelArt.h from the SVGs in
# src/apps_local/scoundrel/art/. Needs rsvg-convert and Pillow.
#
# Card art: game-icons.net, CC BY 3.0 (see art/ATTRIBUTION.md), sizes 48, 64 (room cards) and 96 (desk and menus).
# Marks: Lucide (ISC), sizes 24 and 32. The shelf icon goes to its own header.
set -euo pipefail
REPO="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../.." && pwd)"
cd "$REPO"
ART=src/apps_local/scoundrel/art
OUT=src/apps_local/scoundrel/ScoundrelArt.h
GEN=freeink-sdk/libs/assets/Icons/tools/gen_icons.py
CARDS="$(mktemp)"; MARKS="$(mktemp)"
trap 'rm -f "$CARDS" "$MARKS"' EXIT
python3 "$GEN" --manifest "$ART/cards.txt" --svgdir "$ART" --sizes 48,64,96 --out "$CARDS" >/dev/null
python3 "$GEN" --manifest "$ART/marks.txt" --svgdir "$ART" --sizes 24,32 --out "$MARKS" >/dev/null
{
  printf '#pragma once\n\n'
  printf '// Scoundrel artwork. Generated by tools_local/scoundrel/gen_scoundrel_art.sh; do not edit.\n'
  printf '//\n'
  printf '// Card art: game-icons.net (CC BY 3.0)\n'
  printf '// (see art/ATTRIBUTION.md). Type marks and the shelf icon from Lucide (ISC).\n\n'
  sed '/^#pragma once$/d;s|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.||' "$CARDS"
  sed '/^#pragma once$/d;/#include "Icon.h"/d;s|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.||' "$MARKS"
} > "$OUT"
echo "wrote $OUT"

SHELF=src/apps_local/scoundrel/ScoundrelShelfIcon.h
python3 "$GEN" --manifest "$ART/shelf.txt" --svgdir "$ART" --sizes 32 --out "$SHELF" >/dev/null
sed -i.bak 's|// Generated by libs/assets/Icons/tools/gen_icons.py from Lucide SVGs. Do not edit.|// The Scoundrel shelf icon (Lucide swords). Generated by tools_local/scoundrel/gen_scoundrel_art.sh.|' "$SHELF" && rm -f "$SHELF.bak"
echo "wrote $SHELF"
